// tools/gen-precache.mjs
// Run from the project root after adding or changing files:  node tools/gen-precache.mjs
// It lists every app file for offline use and bumps the cache version.

import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const SKIP = new Set(['node_modules', 'tools', 'supabase', '.git', 'sw.js', 'precache.js', 'README.md']);
const files = [];

(function walk(dir) {
  for (const name of readdirSync(dir).sort()) {
    if (SKIP.has(name) || name.startsWith('.')) continue;
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else files.push('./' + p.split('\\').join('/'));
  }
})('.');

const version = 'edmedia-' + Date.now().toString(36);
const body =
  '// precache.js (generated by tools/gen-precache.mjs)\n\n' +
  "self.PRECACHE_VERSION = '" + version + "';\n\n" +
  'self.PRECACHE_FILES = [\n  \'./\',\n' + files.map((f) => "  '" + f + "',").join('\n') + '\n];\n';

writeFileSync('precache.js', body);
console.log('precache.js written: ' + files.length + ' files, version ' + version);
